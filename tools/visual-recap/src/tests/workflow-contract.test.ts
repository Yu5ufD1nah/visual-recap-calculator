import {readFileSync} from 'node:fs'
import {it,expect} from 'vitest'
const generator=readFileSync('../../.github/workflows/pr-visual-recap.yml','utf8')
const publisher=readFileSync('../../.github/workflows/pr-visual-recap-publish.yml','utf8')
const deployer=readFileSync('../../.github/workflows/pr-visual-recap-site-deploy.yml','utf8')
it('runs PR analysis on trusted base code with read-only privileges',()=>{
 expect(generator).toContain('pull_request:')
 expect(generator).not.toContain('pull_request_target:')
 expect(generator).toContain('ref: ${{ github.event.pull_request.base.sha }}')
 expect(generator).not.toContain('contents: write')
 expect(generator).toContain('github.event.pull_request.head.repo.full_name == github.repository')
 expect(generator).toContain('!github.event.pull_request.draft')
})
it('selects explicit evidence-only mode without disguising configured Copilot failure',()=>{
 expect(generator).toContain('scripts/generate-evidence-only.ts')
 expect(generator).toContain('scripts/generate-recap.ts')
 expect(generator).toContain("steps.mode.outputs.copilot == 'true'")
 expect(generator).toContain("steps.copilot.outcome == 'success'")
 expect(generator).not.toContain('OPENAI_API_KEY')
})
it('limits public processing and publishing to this demo repository',()=>{
 for(const workflow of [generator,publisher,deployer])expect(workflow).toContain("github.repository == 'Yu5ufD1nah/visual-recap-calculator'")
})
it('publishes only validated data with executable viewer built from main',()=>{
 expect(publisher).toContain('workflow_run:')
 expect(publisher).toContain('ref: main')
 expect(publisher).toContain('scripts/verify-run.ts')
 expect(publisher).toContain('Build executable viewer only from trusted main')
 expect(publisher).toContain('VIEWER_ASSETS: dist')
 expect(publisher).toContain('available=false')
 expect(publisher).not.toContain('actions/deploy-pages@')
})
it('separates privileged deployment and reconciles comments only after deployment',()=>{
 expect(publisher).not.toContain('pages: write')
 expect(deployer).toContain('pages: write')
 expect(deployer).toContain('id-token: write')
 expect(deployer).toContain('pull-requests: write')
 expect(deployer).toContain('cancel-in-progress: false')
 expect(deployer).toContain('scripts/reconcile-comments.ts')
 expect(deployer.indexOf('actions/deploy-pages@')).toBeLessThan(deployer.indexOf('scripts/reconcile-comments.ts'))
})
it('deploys calculator before any recap and preserves accumulated recap pages',()=>{
 expect(deployer).toContain('branches: [main]')
 expect(deployer).toContain('clone --depth=1 -b gh-pages')
 expect(deployer).toContain('cp app/index.html app/app.js app/calculator.js app/styles.css site/')
 expect(deployer).toContain('mkdir -p site/recaps')
 expect(deployer).toContain('if [[ "$status" -eq 2 ]]')
 expect(deployer).toContain('exit "$status"')
 expect(deployer).not.toContain('gh-pages >/dev/null 2>&1')
})
